"""Analyze xcresult JSON for the public report-only ``./flaky`` command."""

import argparse
from datetime import datetime, timezone
import glob
import json
from pathlib import Path
import re
import sys
from typing import Iterable, Mapping, Optional, Sequence

from xcode_results import test_cases


def analyze_suite_documents(
    documents: Sequence[Mapping[str, object]],
) -> dict[str, dict[str, object]]:
    stats: dict[str, dict[str, object]] = {}
    for document in documents:
        for case in test_cases(document):
            identifier = case.only_testing_identifier
            record = stats.setdefault(
                identifier,
                {
                    "bundle": case.bundle,
                    "name": case.name,
                    "fails": 0,
                    "seen": 0,
                },
            )
            record["seen"] = int(record["seen"]) + 1
            if case.result == "failed":
                record["fails"] = int(record["fails"]) + 1
    return stats


def tight_counts(tight_directory: Path, index: str) -> tuple[int, int]:
    results: list[str] = []
    tests_json = tight_directory / f"tight_{index}.tests.json"
    if tests_json.exists():
        try:
            with tests_json.open() as stream:
                document = json.load(stream)
            results = [case.result for case in test_cases(document)]
        except Exception as error:
            print(f"warning: couldn't read {tests_json} ({error})", file=sys.stderr)
    if len(results) >= 2:
        return sum(result == "failed" for result in results), len(results)

    summary_json = tight_directory / f"tight_{index}.summary.json"
    if summary_json.exists():
        try:
            with summary_json.open() as stream:
                summary = json.load(stream)
            failed = int(summary.get("failedTests") or 0)
            passed = int(summary.get("passedTests") or 0)
            total = failed + passed
            if total > 0:
                return failed, total
        except Exception as error:
            print(f"warning: couldn't read {summary_json} ({error})", file=sys.stderr)

    if results:
        return sum(result == "failed" for result in results), len(results)
    return 0, 0


def flaky_rows(
    suite: Mapping[str, Mapping[str, object]],
    tight: Mapping[str, tuple[int, int]],
    suite_runs: int,
) -> list[dict[str, object]]:
    rows = []
    for identifier, record in suite.items():
        suite_failures = int(record["fails"])
        seen = int(record["seen"])
        tight_failures, tight_total = tight.get(identifier, (0, 0))
        combined_failures = suite_failures + tight_failures
        combined_passes = (seen - suite_failures) + (tight_total - tight_failures)
        if combined_failures <= 0 or combined_passes <= 0:
            continue
        rates = [suite_failures / suite_runs if suite_runs else 0.0]
        if tight_total > 0:
            rates.append(tight_failures / tight_total)
        rows.append(
            {
                "id": identifier,
                "bundle": record["bundle"],
                "name": record["name"],
                "suite_fail": suite_failures,
                "suite_runs": suite_runs,
                "tight_fail": tight_failures,
                "tight_total": tight_total,
                "flake_rate": sum(rates) / len(rates),
            }
        )
    rows.sort(
        key=lambda row: (
            -float(row["flake_rate"]),
            -int(row["suite_fail"]),
            str(row["id"]),
        )
    )
    return rows


def console_report(rows: Sequence[Mapping[str, object]], top: int) -> str:
    shown = rows[:top]
    if not shown:
        return "No flaky tests detected."
    lines = [
        f"{len(rows)} flaky test(s) detected"
        + (f" (showing top {top})" if len(rows) > top else "")
        + ":",
        "",
    ]
    for row in shown:
        lines.append(
            f"  {float(row['flake_rate']) * 100:5.1f}%  "
            f"suite {row['suite_fail']}/{row['suite_runs']}  "
            f"tight {_tight_cell(row)}  {row['id']}"
        )
    return "\n".join(lines)


def markdown_report(
    rows: Sequence[Mapping[str, object]],
    *,
    top: int,
    suite_runs: int,
    iterations: int,
    relaunch: str,
    device: str,
    os_version: str,
    generated_at: datetime,
) -> str:
    shown = rows[:top]
    now = generated_at.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# Flaky tests",
        "",
        "<!-- Generated by ./flaky — do not hand-edit. Re-run ./flaky to refresh. -->",
        "",
        f"_Last run: {now} · suite runs: {suite_runs} · tight-loop "
        f"iterations: {iterations} · relaunch: {relaunch} · "
        f"destination: {device} / iOS {os_version}._",
        "",
        "A test is listed here only when it produced **both** passes and failures across the",
        "suite runs and the per-test tight loop — i.e. it is genuinely non-deterministic.",
        "Tests that always pass, or that always fail (broken, not flaky), are omitted.",
        "The flake rate averages the suite failure rate and the tight-loop failure rate.",
        "",
        "## Detected flaky tests",
        "",
    ]
    if shown:
        lines.extend(
            [
                "| Test | Bundle | Suite fails | Tight-loop fails | Flake rate |",
                "|------|--------|-------------|------------------|------------|",
            ]
        )
        for row in shown:
            lines.append(
                f"| `{row['id']}` | {row['bundle']} | "
                f"{row['suite_fail']}/{row['suite_runs']} | {_tight_cell(row)} | "
                f"{float(row['flake_rate']) * 100:.0f}% |"
            )
        if len(rows) > top:
            lines.extend(
                [
                    "",
                    f"_(+{len(rows) - top} more not shown; raise `--top` to list them.)_",
                ]
            )
    else:
        lines.append("None detected in the latest run.")
    lines.append("")
    return "\n".join(lines)


def _tight_cell(row: Mapping[str, object]) -> str:
    if int(row["tight_total"]):
        return f"{row['tight_fail']}/{row['tight_total']}"
    return "n/a"


def main(arguments: Optional[Iterable[str]] = None) -> int:
    parser = argparse.ArgumentParser()
    subparsers = parser.add_subparsers(dest="command", required=True)

    analyze = subparsers.add_parser("analyze-suite")
    analyze.add_argument("--suite-dir", required=True, type=Path)
    analyze.add_argument("--suspects", required=True, type=Path)
    analyze.add_argument("--counts", required=True, type=Path)

    report = subparsers.add_parser("report")
    report.add_argument("--counts", required=True, type=Path)
    report.add_argument("--tight-dir", required=True, type=Path)
    report.add_argument("--suite-runs", required=True, type=int)
    report.add_argument("--iterations", required=True, type=int)
    report.add_argument("--top", required=True, type=int)
    report.add_argument("--update", action="store_true")
    report.add_argument("--device", required=True)
    report.add_argument("--os", required=True)
    report.add_argument("--relaunch", required=True)
    report.add_argument("--output", type=Path, default=Path("FLAKY_TESTS.md"))

    options = parser.parse_args(arguments)
    if options.command == "analyze-suite":
        documents = []
        files = sorted(options.suite_dir.glob("run_*.json"))
        if not files:
            print("warning: no suite result files to analyze", file=sys.stderr)
        for path in files:
            try:
                with path.open() as stream:
                    documents.append(json.load(stream))
            except Exception as error:
                print(f"warning: couldn't read {path} ({error})", file=sys.stderr)
        stats = analyze_suite_documents(documents)
        suspects = sorted(
            identifier for identifier, record in stats.items() if record["fails"] > 0
        )
        options.suspects.write_text("".join(identifier + "\n" for identifier in suspects))
        options.counts.write_text(json.dumps(stats))
        print(f"  {len(stats)} distinct tests seen across the suite runs")
        print(f"  {len(suspects)} suspect(s) failed at least once")
    elif options.command == "report":
        try:
            with options.counts.open() as stream:
                suite = json.load(stream)
        except Exception as error:
            print(f"warning: couldn't read suite counts ({error})", file=sys.stderr)
            suite = {}
        tight = {}
        for identifier_path in glob.glob(str(options.tight_dir / "tight_*.id")):
            match = re.search(r"tight_(\d+)\.id$", identifier_path)
            if not match:
                continue
            identifier = Path(identifier_path).read_text().strip()
            tight[identifier] = tight_counts(options.tight_dir, match.group(1))
        rows = flaky_rows(suite, tight, options.suite_runs)
        print(console_report(rows, options.top))
        if options.update:
            options.output.write_text(
                markdown_report(
                    rows,
                    top=options.top,
                    suite_runs=options.suite_runs,
                    iterations=options.iterations,
                    relaunch=options.relaunch,
                    device=options.device,
                    os_version=options.os,
                    generated_at=datetime.now(timezone.utc),
                )
            )
            print("\nWrote FLAKY_TESTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
