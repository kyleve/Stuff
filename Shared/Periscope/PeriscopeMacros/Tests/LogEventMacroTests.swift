@Test(
    arguments: ["exportedValue", "exportDescription", "`exportedValue`", "`exportDescription`"],
    ["var", "func"],
)
func rejectsExportProjectionCollision(name: String, kind: String) {
    let member = kind == "var" ? "var \(name): String { \"value\" }" : "func \(name)() {}"
    assertMacroExpansion(
        """
        @LogScope("Sample")
        enum SampleLog {
            @LogEvent("event", message: "Event")
            struct Event {
                \(member)
            }
        }
        """,
        expandedSource: """
        @LogScope("Sample")
        enum SampleLog {
            struct Event {
                \(member)
            }
        }

        extension SampleLog.Event: PeriscopeCore.LogEvent {
        }
        """,
        diagnostics: [DiagnosticSpec(
            message: "\(name.filter { $0 != "`" }) is generated by @LogEvent",
            line: 5,
            column: 9,
        )],
        macros: ["LogEvent": LogEventMacro.self],
    )
}

