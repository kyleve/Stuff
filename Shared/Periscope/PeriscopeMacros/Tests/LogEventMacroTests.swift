@Test func rejectsConditionalEventMembers() {
    let declaration: DeclSyntax = """
    struct Event {
        #if DEBUG
        @LogField(exposure: .shareable, kind: .count) var count: String
        #endif
    }
    """
    let parsed = LogEventMacro.parseFields(declaration.cast(StructDeclSyntax.self))
    #expect(parsed.hasError)
    #expect(parsed.diagnostics.map(\.id) == ["conditional-event-member"])
}

