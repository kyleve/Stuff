@Test(arguments: ["\"count\", ", ""])
func expandsClassifiedEventAndLogMethod(key: String) {
    assertMacroExpansion(
        """
        @LogScope("Sample")
        enum SampleLog {
            @LogEvent("counted", level: .notice, message: "Counted")
            struct Counted {
                @LogField(\(key)exposure: .shareable, kind: .count)
                var count: Int
            }
        }
        """,
        expandedSource: """
        enum SampleLog {
            struct Counted {
                @LogField(\(key)exposure: .shareable, kind: .count)
                var count: Int

                static let eventName = SampleLog.scopeName + ".counted"

                static let eventVersion = 1

                private enum CodingKeys: String, CodingKey {
                        case count = "count"
                }

                init(
                        count: PeriscopeCore.ClassifiedLogInput<PeriscopeCore.LogFieldPolicy.Shared, PeriscopeCore.LogFieldPolicy.Count, Int>
                ) {
                        self._count = PeriscopeCore.LogField(wrappedValue: count.value, "count", exposure: .shareable, kind: .count)
                }

                var classifiedFields: [PeriscopeCore.ClassifiedLogField] {
                    var fields: [PeriscopeCore.ClassifiedLogField] = []
                        if let field = PeriscopeCore.LogFieldProjection.count(self.count, key: PeriscopeCore.LogFieldKey("count")) {
                        fields.append(field)
                    }
                    return fields
                }

                var exportDescription: PeriscopeCore.LogExportDescription {
                    PeriscopeCore.LogExportDescription.object([
                        PeriscopeCore.LogExportField(PeriscopeCore.LogFieldKey("count"), value: self.count, requirements: .classified(exposure: .shareable, kind: .count))
                    ])
                }

                struct LogMethod {
                    fileprivate let log: PeriscopeCore.Log<SampleLog>

                    func callAsFunction(
                        count: PeriscopeCore.ClassifiedLogInput<PeriscopeCore.LogFieldPolicy.Shared, PeriscopeCore.LogFieldPolicy.Count, Int>,
                        attachments: [PeriscopeCore.LogAttachment] = [],
                        function: StaticString = #function,
                        fileID: StaticString = #fileID
                    ) {
                        self.log.record(
                            SampleLog.Counted(
                                count: count
                            ),
                            attachments: attachments,
                            function: function,
                            fileID: fileID
                        )
                    }
                }

                func exportedValue(using policy: PeriscopeCore.LogExportPolicy) throws -> PeriscopeCore.JSONValue {
                    try exportDescription.exportedValue(using: policy)
                }

                var level: PeriscopeCore.LogLevel {
                    .notice
                }

                var message: String {
                    "Counted"
                }

                var externalID: String? {
                    nil
                }

                static var isProtectedFromDropping: Bool {
                    false
                }
            }

            static let scopeName = "Sample"

            struct LogMethods {
                fileprivate let log: PeriscopeCore.Log<SampleLog>

                var `counted`: Counted.LogMethod {
                    Counted.LogMethod(log: log)
                }
            }

            static func makeLogMethods(_ log: PeriscopeCore.Log<SampleLog>) -> LogMethods {
                LogMethods(log: log)
            }
        }

        extension SampleLog.Counted: PeriscopeCore.LogEvent {
        }

        extension SampleLog: PeriscopeCore.LogScopeDefinition {
        }
        """,
        macros: macros,
    )
}

